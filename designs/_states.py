# more states come from the Game Day group modules (designs/_gameday_<group>.py), so
# parallel work on different states never edits the same file
PROJECTION = {}     # name: Albers (lat1, lat2, lon0, lat0); others equirectangular
for _p in sorted(Path(__file__).parent.glob("_gameday_*.py")):
    _m = importlib.import_module(_p.stem)
    STATES.update(_m.STATES)
    PROJECTION.update(getattr(_m, "PROJECTION", {}))


def _dense(ring, step=0.05):
    """Points every `step` degrees along a ring: a border along a parallel is an arc in
    Albers, not the straight chord between two corners."""
    a, b = ring, np.roll(ring, -1, axis=0)
    out = [a[i] + (b[i] - a[i]) * t for i in range(len(a))
           for t in np.arange(0, 1, step / max(np.abs(b[i] - a[i]).max(), step))]
    return np.array(out)


def _albers(lon, lat, lat1, lat2, lon0, lat0):
    """Spherical Albers equal-area, centred on the state's own meridian so it stands
    upright: true proportions and coastline, without the tilt a whole-US map gives."""
    f1, f2, f0, f = (np.radians(v) for v in (lat1, lat2, lat0, lat))
    n = (np.sin(f1) + np.sin(f2)) / 2
    c = np.cos(f1) ** 2 + 2 * n * np.sin(f1)
    rho0 = np.sqrt(c - 2 * n * np.sin(f0)) / n
    rho = np.sqrt(c - 2 * n * np.sin(f)) / n
    t = n * np.radians(lon - lon0)
    return np.c_[rho * np.sin(t), rho0 - rho * np.cos(t)]


def state_shape(name, height):
    """The state as one shape `height` mm tall. An entry is one ring of (lon, lat), or a
    list of rings for a state in several pieces (Michigan's peninsulas, Hawaii)."""
    entry = STATES[name]
    rings = [np.array(r) for r in (entry if isinstance(entry[0][0], (list, tuple)) else [entry])]
    if name in PROJECTION:
        lat1, lat2, _, lat0 = PROJECTION[name]
        lon0 = (min(r[:, 0].min() for r in rings) + max(r[:, 0].max() for r in rings)) / 2
        shape = unary_union([poly(_albers(*_dense(r).T, lat1, lat2, lon0, lat0)).buffer(0) for r in rings])
    else:
        ll = np.vstack(rings)
        lat0 = (ll[:, 1].min() + ll[:, 1].max()) / 2
        k = np.cos(np.radians(lat0))
        shape = unary_union([poly(np.c_[r[:, 0] * k, r[:, 1]]).buffer(0) for r in rings])
    x0, y0, x1, y1 = shape.bounds
    return centered(scale(shape, height / (y1 - y0)))
