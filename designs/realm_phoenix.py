def checks(p):
    return standard_checks(p, 5, 16000)


BORDER = 1.6


def tube(points, radii, samples=12):
    """A shape swept along a smooth path through `points`, radius interpolated along
    its length from `radii` (one per control point)."""
    path = spline(np.asarray(points, float), samples)
    seg = np.r_[0, np.cumsum(np.linalg.norm(np.diff(path, axis=0), axis=1))]
    idx = [int(np.argmin(np.linalg.norm(path - c, axis=1))) for c in np.asarray(points, float)]
    r = np.interp(seg, seg[idx], radii)
    parts = [union(circle(*path[i], max(r[i], 0.05), 32),
                   circle(*path[i + 1], max(r[i + 1], 0.05), 32)).convex_hull
             for i in range(len(path) - 1)]
    return union(*parts)


def feather(base, deg, length, width, curl):
    """(shape, fill angle): a tapered flame feather from `base` along `deg`, its tip
    flicked `curl` mm to the left of its direction."""
    a = np.radians(deg)
    u, n = np.array([np.cos(a), np.sin(a)]), np.array([-np.sin(a), np.cos(a)])
    b = np.asarray(base, float)
    pts = [b, b + u * length * 0.35, b + u * length * 0.72 + n * curl * 0.35, b + u * length + n * curl]
    return tube([tuple(p) for p in pts], [width * 0.3, width / 2, width * 0.36, 0.3]), deg


def tiers(base, angles, lengths, width, curl, scales=(1.0, 0.68, 0.4), offset=(0, 0.5, 0.0)):
    """Three tiers of feathers fanned from `base`: [[(shape, angle)] per tier], long
    first. Middle-tier feathers sit between the long ones."""
    out = []
    for k, sc in enumerate(scales):
        step = angles[1] - angles[0]
        tier = []
        for i, (a, L) in enumerate(zip(angles, lengths)):
            a2 = a + offset[k] * step
            if k == 1 and i == len(angles) - 1:
                break
            if k == 2 and i % 2:
                continue
            Lk = np.interp(a2, angles, lengths) * sc
            tier.append(feather(base, a2, Lk, width * (1.0 if k == 0 else 1.1), curl(a2) * sc))
        out.append(tier)
    return out


def mirror(item):
    g, a = item
    return mirror_x(g), 180 - a


def shapes():
    # right wing; the left is its mirror
    wing = tiers((9, 14), list(np.linspace(8, 66, 8)), [36, 42, 48, 53, 56, 55, 50, 41], 10.0,
                 lambda a: 3.0)
    tail = tiers((0, -6), [-128, -110, -90, -70, -52], [32, 42, 47, 42, 32], 9.0,
                 lambda a: -4.0 if a > -90 else (4.0 if a < -90 else 0.0))
    tiers_ = []
    for k in range(3):
        t = wing[k] + [mirror(f) for f in wing[k]]
        # tail: only the right half is generated by angle, it is already symmetric
        t += tail[k]
        tiers_.append(t)
    body = union(smooth([(0, -11), (5, -5), (9, 5), (10, 15), (6, 24), (3, 34), (-2, 34), (-5, 24),
                         (-10, 15), (-9, 5), (-5, -5)], 8).buffer(0))
    head = circle(2.2, 38.5, 5.6, 64)
    beak = poly([(6.6, 41.0), (12.2, 38.0), (6.8, 35.6)])
    eye = circle(3.8, 39.6, 1.2, 32)
    crest = [feather((0.5, 42.0), a, L, 4.2, c) for a, L, c in [(78, 13, 2.5), (104, 17, 2.5), (130, 13, 2.5)]]
    return tiers_, body, head, beak, eye, crest


def art():
    d = Design()
    tiers_, body, head, beak, eye, crest = shapes()
    tier_shapes = [union(*[g for g, _ in t]) for t in tiers_]
    bird = union(body, head)
    silhouette = union(*tier_shapes, bird, beak, *[g for g, _ in crest])
    band = silhouette.exterior.buffer(BORDER / 2)

    def fill(shape, color, **kw):
        g = knockout(shape, band)
        if not g.is_empty:
            d.fill(g, C_[color], **kw)

    above = lambda k: union(bird, beak, *[g for g, _ in crest], *tier_shapes[k + 1:])
    for k, color in enumerate(("red", "flame", "yellow")):
        cover = above(k)
        seen = cover
        # later feathers of a tier lap over earlier ones; each fills along its length
        # neighbours alternate +-18 deg off their length so they read apart
        for i, (g, a) in enumerate(reversed(tiers_[k])):
            fill(knockout(g, seen), color, angle=a + (18 if i % 2 else -18), name=f"{color} feather")
            seen = union(seen, g)
        if color == "red":
            for g, a in crest:
                fill(knockout(g, head), "red", angle=a, name="crest")
        if color == "flame":
            fill(beak, "flame", angle=0, name="beak")
    fill(knockout(bird, beak, eye), "gold", angle=80, name="body")
    fill(eye, "black", angle=0, underlay=False, name="eye")
    d.outline(silhouette, C_["black"], width=BORDER, name="border")
    return d


def design(p):
    return fit(art(), p.size, hoop_for(p.size))
